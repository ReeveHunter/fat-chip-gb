#!/usr/bin/env python3
"""Build the UI tile set (bank 1) from the public-domain font8x8 by Daniel Hepper.

Tile map:
    0..63    ASCII 32..95, black on white
   64..127   ASCII 32..95, white on black (inverted, for headers / cursor rows)
  128..191   ASCII 32..95, dark grey (labels)
  192..200   meter segments, 0..8 px filled
  201..      UI glyphs (see GLYPHS)
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from cgen import c_array, header  # noqa: E402

HERE = os.path.dirname(__file__)
SRC = os.path.join(HERE, "..", "res", "font8x8_basic.h")
OUT = os.path.join(HERE, "..", "src", "gen", "font.c")
FONT_BANK = 8


def load_font():
    text = open(SRC).read()
    rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2},?\s*){8})\}", text)
    glyphs = [[int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]{2}", r)] for r in rows]
    assert len(glyphs) >= 128
    return glyphs


def tile_from_rows(pix):
    """pix: 8 rows of 8 colour indices (0..3). Returns 16 bytes."""
    out = []
    for row in pix:
        lo = hi = 0
        for x, c in enumerate(row):
            bit = 0x80 >> x
            if c & 1:
                lo |= bit
            if c & 2:
                hi |= bit
        out += [lo, hi]
    return out


def glyph_pix(g, fg, bg):
    pix = []
    for r in range(8):
        b = g[r]
        pix.append([fg if (b >> x) & 1 else bg for x in range(8)])
    return pix


def thin(g):
    """font8x8 strokes are 2px wide; thin them to 1px so text breathes on the
    small screen: in every row, runs of 2 become 1 and longer runs lose their
    rightmost pixel. Then shift right one pixel to centre the narrower glyph."""
    out = []
    for b in g:
        bits = [(b >> x) & 1 for x in range(8)]
        res = [0] * 8
        x = 0
        while x < 8:
            if bits[x]:
                e = x
                while e < 8 and bits[e]:
                    e += 1
                n = e - x
                keep = 1 if n <= 2 else n - 1
                for k in range(x, x + keep):
                    res[k] = 1
                x = e
            else:
                x += 1
        v = sum(bit << i for i, bit in enumerate(res))
        out.append((v << 1) & 0xFF)
    return out


GLYPHS = {
    # name: 8 strings of '.', '1', '2', '3'
    "ARROW": ["........", ".3......", ".33.....", ".333....", ".3333...", ".333....", ".33.....", ".3......"],
    "NOTE": ["....33..", "....3.3.", "....3..3", "....3...", "..333...", ".3333...", ".333....", "........"],
    "DOT": ["........", "........", "........", "...33...", "...33...", "........", "........", "........"],
    "LEFT": ["........", "....3...", "...33...", "..333...", "...33...", "....3...", "........", "........"],
    "RIGHT": ["........", "...3....", "...33...", "...333..", "...33...", "...3....", "........", "........"],
    "BAR": ["........", "........", "........", "........", "33333333", "........", "........", "........"],
    "BACKSP": ["........", "...3333.", "..3....3", ".3..3.3.", "3....3..", ".3..3.3.", "..3....3", "...3333."],
    "SPACE": ["........", "........", "........", "........", "........", "3......3", "33333333", "........"],
    "INVBLANK": ["33333333"] * 8,
    "GREY": ["11111111"] * 8,
}


STYLE = os.environ.get("FONT_STYLE", "bold")


def shape(g):
    return thin(g) if STYLE == "thin" else g


def main():
    font = load_font()
    dim = 3 if STYLE == "bold-dark" else 2
    tiles = []
    for code in range(32, 96):
        tiles += tile_from_rows(glyph_pix(shape(font[code]), 3, 0))
    for code in range(32, 96):
        tiles += tile_from_rows(glyph_pix(shape(font[code]), 0, 3))
    for code in range(32, 96):
        tiles += tile_from_rows(glyph_pix(shape(font[code]), dim, 0))
    for k in range(9):
        pix = []
        for r in range(8):
            row = []
            for x in range(8):
                if 2 <= r <= 5:
                    row.append(3 if x < k else (1 if r in (3, 4) else 0))
                else:
                    row.append(0)
            pix.append(row)
        tiles += tile_from_rows(pix)
    names = []
    for name, rows in GLYPHS.items():
        tiles += tile_from_rows([[int(c) if c != "." else 0 for c in r] for r in rows])
        names.append(name)
    ntiles = len(tiles) // 16
    assert ntiles <= 256

    src = header(FONT_BANK)
    src += f"/* {ntiles} tiles */\n"
    src += c_array("ui_tiles", tiles)
    open(OUT, "w").write(src)

    hdr = ["/* generated by tools/gen_font.py */", "#ifndef FONT_H", "#define FONT_H",
           f"#define UI_TILE_COUNT {ntiles}", f"#define FONT_BANK {FONT_BANK}", "#define T_INV 64", "#define T_DIM 128", "#define T_METER 192"]
    for i, n in enumerate(names):
        hdr.append(f"#define T_{n} {201 + i}")
    hdr.append("#endif")
    open(os.path.join(HERE, "..", "src", "gen", "font.h"), "w").write("\n".join(hdr) + "\n")
    print(f"font: {ntiles} tiles")


if __name__ == "__main__":
    main()
